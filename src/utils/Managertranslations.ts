export type ManagerLanguage = 'en' | 'sv'
export type ManagerTranslations = (typeof managerTranslations)['en']

export const useManagerTranslations = () => {
  const [language, setLanguageState] = useState<ManagerLanguage>('sv')
  const [isInitialized, setIsInitialized] = useState(false)

  /* ── Initialise from localStorage ── */
  useEffect(() => {
    const saved = localStorage.getItem('managerLanguage') as ManagerLanguage | null
    if (saved === 'en' || saved === 'sv') setLanguageState(saved)
    setIsInitialized(true)
  }, [])

  /* ── Setter — persists + broadcasts ── */
  const setLanguage = useCallback((lang: ManagerLanguage) => {
    setLanguageState(lang)
    localStorage.setItem('managerLanguage', lang)
    window.dispatchEvent(new CustomEvent('managerLanguageChanged', { detail: lang }))
  }, [])

  /* ── Listen for cross-component changes ── */
  useEffect(() => {
    const handler = (e: CustomEvent) => setLanguageState(e.detail as ManagerLanguage)
    window.addEventListener('managerLanguageChanged', handler as EventListener)
    return () => window.removeEventListener('managerLanguageChanged', handler as EventListener)
  }, [])

  return {
    language,
    setLanguage,
    t: managerTranslations[language] as ManagerTranslations,
    isInitialized,
  }
}

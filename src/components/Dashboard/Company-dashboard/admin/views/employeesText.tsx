export type EmployeesTx = typeof en
export const employeesTx = (language: string | undefined): EmployeesTx => (language === 'en' ? en : sv)

export function relativeTime(iso: string | null, tx: EmployeesTx, language: string) {
  if (!iso) return tx.never
  const min = Math.round((Date.now() - new Date(iso).getTime()) / 60_000)
  if (min < 2) return tx.justNow
  if (min < 60) return tx.minAgo(min)
  const h = Math.round(min / 60)
  if (h < 24) return tx.hAgo(h)
  const d = Math.round(h / 24)
  if (d < 14) return tx.daysAgo(d)
  return formatDate(iso, language)
}

export const formatDate = (iso: string | null | undefined, language: string) =>
  iso ? new Date(iso).toLocaleDateString(language === 'en' ? 'en-GB' : 'sv-SE', { day: 'numeric', month: 'short', year: 'numeric' }) : '—'

export const initials = (name: string) =>
  name.split(/\s+/).filter(Boolean).slice(0, 2).map((w) => w[0]!.toUpperCase()).join('') || '?'
